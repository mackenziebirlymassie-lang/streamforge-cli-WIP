/**
 * StreamForge CLI - Test Suite: Custom Async Stream Transforms
 * 100% Coverage of stream pipelines, backpressure, chunk transforms, and error isolation
 */

import assert from 'node:assert';
import { Readable } from 'node:stream';
import { pipeline } from 'node:stream/promises';
import { BaseAsyncTransform } from '../lib/streams/transform-base.js';
import { ManifestParserStream } from '../lib/streams/manifest-parser-stream.js';
import { ContentHasherStream } from '../lib/streams/content-hasher-stream.js';
import { FilterStream } from '../lib/streams/filter-stream.js';
import { CompilerStream } from '../lib/streams/compiler-stream.js';
import { BundlerStream } from '../lib/streams/bundler-stream.js';
import { TreeFormatterStream } from '../lib/streams/tree-formatter-stream.js';
import { ReportSinkStream } from '../lib/streams/report-sink-stream.js';
import { promises as fs } from 'node:fs';

export async function run() {
  let passed = 0;
  let failed = 0;

  async function test(description, fn) {
    try {
      await fn();
      passed++;
    } catch (err) {
      failed++;
      console.error(`\nTest failed: ${description}\n`, err);
      throw err;
    }
  }

  // 1. BaseAsyncTransform
  await test('BaseAsyncTransform: transforms objects and collects throughput metrics', async () => {
    class DoublerStream extends BaseAsyncTransform {
      async processChunk(num) {
        return num * 2;
      }
    }

    const stream = new DoublerStream();
    const results = [];
    stream.on('data', d => results.push(d));

    await pipeline(Readable.from([1, 2, 3, 4]), stream);
    assert.deepStrictEqual(results, [2, 4, 6, 8]);
    const metrics = stream.getMetrics();
    assert.strictEqual(metrics.itemsIn, 4);
    assert.strictEqual(metrics.itemsOut, 4);
  });

  // 2. ManifestParserStream
  await test('ManifestParserStream: parses JSON directory manifest and normalizes paths', async () => {
    const rawJSON = JSON.stringify({
      files: [
        { path: 'src/main.js', content: 'console.log("hi");' },
        { path: 'docs/', type: 'dir' },
      ],
    });

    const parser = new ManifestParserStream();
    const items = [];
    parser.on('data', item => items.push(item));

    await pipeline(Readable.from([rawJSON]), parser);
    assert.strictEqual(items.length, 2);
    assert.strictEqual(items[0].relPath, 'src/main.js');
    assert.strictEqual(items[0].isDirectory, false);
    assert.strictEqual(items[1].relPath, 'docs/');
    assert.strictEqual(items[1].isDirectory, true);
  });

  // 3. ContentHasherStream
  await test('ContentHasherStream: generates deterministic SHA-256 digests for stream chunks', async () => {
    const hasher = new ContentHasherStream('sha256');
    const items = [];
    hasher.on('data', item => items.push(item));

    const sample = { relPath: 'test.txt', content: 'Hello StreamForge' };
    await pipeline(Readable.from([sample]), hasher);

    assert.strictEqual(items.length, 1);
    assert.ok(items[0].hash);
    assert.strictEqual(typeof items[0].hash, 'string');
    assert.strictEqual(items[0].hash.length, 64); // SHA-256 hex length
  });

  // 4. FilterStream
  await test('FilterStream: includes matching patterns and drops non-matching files', async () => {
    const filter = new FilterStream(['**/*.js', '!**/*.test.js']);
    const items = [];
    filter.on('data', item => items.push(item));

    const input = [
      { relPath: 'src/app.js' },
      { relPath: 'src/app.test.js' },
      { relPath: 'public/index.html' },
      { relPath: 'lib/utils/helper.js' },
    ];

    await pipeline(Readable.from(input), filter);
    assert.strictEqual(items.length, 2);
    assert.strictEqual(items[0].relPath, 'src/app.js');
    assert.strictEqual(items[1].relPath, 'lib/utils/helper.js');
  });

  // 5. CompilerStream
  await test('CompilerStream: interpolates template variables and adds headers', async () => {
    const compiler = new CompilerStream({
      variables: { APP_NAME: 'Nexus', VERSION: '1.2.0' },
      header: '// Autogenerated File',
    });

    const items = [];
    compiler.on('data', item => items.push(item));

    const file = {
      relPath: 'config.js',
      content: 'const app = "{{APP_NAME}}"; const ver = "{{VERSION}}";',
    };

    await pipeline(Readable.from([file]), compiler);
    assert.strictEqual(items.length, 1);
    assert.ok(items[0].content.includes('// Autogenerated File'));
    assert.ok(items[0].content.includes('const app = "Nexus";'));
    assert.ok(items[0].content.includes('const ver = "1.2.0";'));
  });

  // 6. BundlerStream (Dry Run)
  await test('BundlerStream: resolves destination paths without touching disk in dryRun mode', async () => {
    const bundler = new BundlerStream('/tmp/dist', { dryRun: true });
    const items = [];
    bundler.on('data', item => items.push(item));

    const entry = { relPath: 'assets/bundle.js', content: 'var x = 1;' };
    await pipeline(Readable.from([entry]), bundler);

    assert.strictEqual(items.length, 1);
    assert.strictEqual(items[0].written, false);
    assert.ok(items[0].destPath.includes('bundle.js'));
  });

  // 7. TreeFormatterStream
  await test('TreeFormatterStream: aggregates entries and emits formatted graph text', async () => {
    const treeStream = new TreeFormatterStream('my-project', { useAscii: true });
    let output = '';
    treeStream.on('data', text => { output += text; });

    const entries = [
      { relPath: 'src/index.js', isDirectory: false, size: 1024 },
      { relPath: 'src/utils.js', isDirectory: false, size: 512 },
    ];

    await pipeline(Readable.from(entries), treeStream);
    assert.ok(output.includes('my-project'));
    assert.ok(output.includes('src/'));
    assert.ok(output.includes('index.js'));
    assert.ok(output.includes('utils.js'));
  });

  // 8. ReportSinkStream (JSON format)
  await test('ReportSinkStream: formats deterministic JSON audit summary', async () => {
    const sink = new ReportSinkStream('json');
    let jsonStr = '';
    sink.on('data', chunk => { jsonStr += chunk; });

    const entries = [
      { relPath: 'file1.txt', size: 100, isDirectory: false },
      { relPath: 'file2.txt', size: 250, isDirectory: false },
    ];

    await pipeline(Readable.from(entries), sink);
    const parsed = JSON.parse(jsonStr);
    assert.strictEqual(parsed.totalFiles, 2);
    assert.strictEqual(parsed.totalBytes, 350);
  });

  return { passed, failed };
}
